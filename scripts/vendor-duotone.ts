/**
 * Re-vendor the BoldDuotone subset used by `src/components/icons`.
 *
 * reicon-react (npm) ships only Outline and Filled. The duotone variant the
 * reicon website calls "BoldDuotone (Beta)" is loaded from a lazy chunk on
 * reicon.dev, not published to npm. Its artwork is the same family as
 * Filled — the same base path plus a detail path at opacity 0.5 — so a
 * duotone icon next to a Filled fallback still reads as one set.
 *
 * This script fetches the chunk, keeps only the glyphs listed in ICON_NAMES,
 * and rewrites `src/components/icons/duotone-data.ts`. Re-run it after adding
 * an icon to the wrapper:
 *
 *     npm run duotone:vendor
 *
 * Source: https://reicon.dev  License: MIT (same as reicon-react)
 */
import { writeFileSync } from "node:fs"
import { join } from "node:path"

const SOURCE = "https://reicon.dev/assets/icon-duotone-zanwk-kk.js"

/** Reicon names the wrapper uses, matched by kebab-case key. */
const ICON_NAMES = [
  "Menu",
  "Logout",
  "AlertCircle",
  "InfoCircle",
  "Inbox",
  "User",
  "Telescope",
  "Gift",
  "Palette",
  "Server",
  "ShieldCheck",
  "Database",
  "Cloud",
]

const kebab = (name: string): string => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()

const run = async () => {
  const response = await fetch(SOURCE)
  if (!response.ok) throw new Error(`fetch failed: ${response.status}`)
  const text = await response.text()

  const match = text.match(/JSON\.parse\('([\s\S]*?)'\),e=/)
  if (!match?.[1]) throw new Error("duotone payload not found in chunk")

  const data = JSON.parse(match[1].replace(/\\"/g, '"')) as Record<string, { code: string }>

  const entries: [string, string][] = []
  for (const name of ICON_NAMES) {
    const key = kebab(name)
    const icon = data[key]
    if (!icon) throw new Error(`duotone art missing for ${name} (key "${key}")`)
    entries.push([key, icon.code])
  }

  const body = entries
    .map(([key, code]) => `  ${JSON.stringify(key)}: ${JSON.stringify(code)},`)
    .join("\n")

  const file = `/**
 * BoldDuotone subset, vendored from reicon.dev (MIT).
 * Generated by \`npm run duotone:vendor\` — do not edit by hand.
 * Keys are kebab-case reicon names; a glyph absent here falls back to Filled.
 */
export const DUOTONE: Record<string, string> = {
${body}
}
`
  const target = join(process.cwd(), "src", "components", "icons", "duotone-data.ts")
  writeFileSync(target, file)
  console.log(`wrote ${entries.length} duotone glyphs to ${target}`)
}

run().catch((error) => {
  console.error(error)
  process.exit(1)
})
